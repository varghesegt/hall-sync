-- V12: Add Claims Engine Tables

CREATE TABLE college_distances (
    id BIGSERIAL PRIMARY KEY,
    institution_code VARCHAR(10),
    institution_name VARCHAR(500) NOT NULL,
    place VARCHAR(200),
    distance_km DECIMAL(10,2) NOT NULL
);

CREATE TABLE claim_records (
    id BIGSERIAL PRIMARY KEY,
    batch_id UUID NOT NULL,
    serial_number INTEGER,
    exam_month VARCHAR(255),
    valuation_date DATE,
    exam_season VARCHAR(255),
    is_government_holiday BOOLEAN DEFAULT FALSE,
    sessions_attended VARCHAR(255),
    board_name VARCHAR(255),
    post_held VARCHAR(255) NOT NULL,
    mobile_no VARCHAR(255),
    name_title VARCHAR(255),
    staff_name VARCHAR(255) NOT NULL,
    faculty_type VARCHAR(255),
    designation VARCHAR(255),
    institution_name VARCHAR(255),
    institution_code VARCHAR(255),
    issue_reg_page_no VARCHAR(255),
    bank_account_number VARCHAR(255),
    ifsc_code VARCHAR(255),
    bank_name VARCHAR(255),
    branch VARCHAR(255),
    distance_km DECIMAL(10,2),
    total_scripts INTEGER DEFAULT 0,
    fn_scripts INTEGER DEFAULT 0,
    an_scripts INTEGER DEFAULT 0,
    script_amount DECIMAL(12,2) DEFAULT 0,
    travelling_allowance DECIMAL(12,2) DEFAULT 0,
    dearness_allowance DECIMAL(12,2) DEFAULT 0,
    total_amount DECIMAL(12,2) DEFAULT 0,
    amount_in_words VARCHAR(500),
    max_scripts_valued INTEGER,
    max_scripts_amount DECIMAL(12,2),
    ten_percent_amount DECIMAL(12,2),
    overall_script_amount DECIMAL(12,2),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE script_details (
    id BIGSERIAL PRIMARY KEY,
    claim_record_id BIGINT NOT NULL REFERENCES claim_records(id) ON DELETE CASCADE,
    session_type VARCHAR(50) NOT NULL,
    serial_number INTEGER,
    subject_code VARCHAR(255),
    no_of_scripts INTEGER DEFAULT 0
);

